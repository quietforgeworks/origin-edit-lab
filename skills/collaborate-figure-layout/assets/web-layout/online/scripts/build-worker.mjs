import { readFile, writeFile, mkdir, cp, lstat, realpath } from 'node:fs/promises';
import { resolve, relative as relativePath, isAbsolute } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const dist = resolve(root, 'dist');
if (!(await lstat(dist)).isDirectory() || (await lstat(dist)).isSymbolicLink()) throw Error('dist must be a real directory');
const realDist = await realpath(dist);
if (!(await lstat(resolve(dist, 'project.json'))).isFile() || (await lstat(resolve(dist, 'project.json'))).isSymbolicLink()) throw Error('project.json must be a regular file, not a symlink');
const project = JSON.parse(await readFile(resolve(dist, 'project.json'), 'utf8'));
const manifest = JSON.parse(await readFile(resolve(root, '.openai/hosting.json'), 'utf8'));
if (manifest.static || manifest.d1 !== 'DB' || !manifest.project_id) throw Error('Expected existing Worker Site with DB binding');
if (project.panels.some(panel => panel.sourceBindings || panel.sourceAssetIds)) throw Error('Private source bindings must not enter hosted artifacts');

// Preserve the established tracked dist frontend paths. Only server/ and .openai/
// are generated. Static bytes are embedded in the ESM Worker, without an asset binding.
const assets = {};
const types = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.json': 'application/json; charset=utf-8', '.png': 'image/png' };
async function add(relative) {
  if (typeof relative !== 'string' || !relative || relative.includes('\\') || relative.includes('\0') || isAbsolute(relative) || relative.split('/').some(part => !part || part === '.' || part === '..')) throw Error('Invalid relative asset path');
  const path = resolve(dist, relative);
  for (let current = dist, segments = relative.split('/'), i = 0; i < segments.length; i++) {
    current = resolve(current, segments[i]);
    if ((await lstat(current)).isSymbolicLink()) throw Error(`Symlink asset is not permitted: ${relative}`);
  }
  const real = await realpath(path);
  const inside = relativePath(realDist, real);
  if (!inside || inside.startsWith('..') || isAbsolute(inside) || !(await lstat(path)).isFile()) throw Error(`Asset must be a regular file inside dist: ${relative}`);
  const extension = relative.slice(relative.lastIndexOf('.')).toLowerCase();
  if (!types[extension]) throw Error(`Unsupported static asset: ${relative}`);
  const bytes = await readFile(path);
  if (extension === '.png' && !bytes.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]))) throw Error(`Preview is not a PNG: ${relative}`);
  assets[`/${relative}`] = { type: types[extension], bytes: bytes.toString('base64') };
}
for (const name of ['index.html', 'app.js', 'style.css', 'project.json']) await add(name);
for (const preview of [...new Set(project.panels.map(panel => panel.preview).filter(value => value !== undefined))].sort()) {
  if (typeof preview !== 'string' || !/\.png$/i.test(preview)) throw Error('Panel previews must be relative PNG paths');
  await add(preview);
}
const code = await readFile(resolve(root, 'worker/index.js'), 'utf8');
const validation = await readFile(resolve(root, 'worker/layout-validation.js'), 'utf8');
const bundled = [
  '// Generated by scripts/build-worker.mjs. Do not edit this file.',
  `const PROJECT = ${JSON.stringify(project)};`,
  `const STATIC_ASSETS = ${JSON.stringify(assets)};`,
  validation.replace(/^export /gm, ''),
  code.replace("import { validateLayout, LayoutValidationError } from './layout-validation.js';\n", ''),
].join('\n');
await mkdir(resolve(dist, 'server'), { recursive: true });
await mkdir(resolve(dist, '.openai'), { recursive: true });
await writeFile(resolve(dist, 'server/index.js'), bundled);
await writeFile(resolve(dist, '.openai/hosting.json'), JSON.stringify(manifest, null, 2) + '\n');
await cp(resolve(root, 'drizzle'), resolve(dist, '.openai/drizzle'), { recursive: true });
console.log(`Built Worker with ${Object.keys(assets).length} preserved static assets (${Buffer.byteLength(bundled)} bytes)`);
